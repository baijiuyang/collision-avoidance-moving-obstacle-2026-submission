'''
File locations used by all notebooks and scripts.

Download the raw data from the data repository (see README.md, "Data") into
the `data/` folder of this repository, or set the environment variable
MOVOBST_DATA_DIR to the folder that holds the downloaded files.
'''
import os

REPO_DIR = os.path.dirname(os.path.abspath(__file__))

# Raw data, as deposited in the data repository
DATA_DIR = os.environ.get('MOVOBST_DATA_DIR', os.path.join(REPO_DIR, 'data'))
COHEN_MOVOBST1_RAW = os.path.join(DATA_DIR, 'Cohen_movObst1_rawData.csv')    # Experiment 1
COHEN_MOVOBST2_RAW = os.path.join(DATA_DIR, 'Cohen_movObst2_rawData.csv')    # Experiment 2
FAJEN_STEER1A_RAW_DIR = os.path.join(DATA_DIR, 'F&W2003_Exp1a_rawData')     # Goal model (Fajen & Warren, 2003)

# Generated by 01_import_data.ipynb
PROCESSED_DIR = os.path.join(REPO_DIR, 'data', 'processed')

# Generated by the notebooks, simulate_pass_order_errors.py, fitting.py and stats/*.R
RESULTS_DIR = os.path.join(REPO_DIR, 'results')
FITTING_DIR = os.path.join(RESULTS_DIR, 'fitting')


def processed_path(name):
    '''Path of a processed data file, e.g. processed_path('Cohen_movObst1_data').'''
    return os.path.join(PROCESSED_DIR, name + '.pickle')
